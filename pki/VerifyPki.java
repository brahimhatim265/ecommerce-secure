    private static Path resolvePkiDir(String[] args) {
        if (args.length > 0) {
            return Paths.get(args[0]).toAbsolutePath().normalize();
        }
        Path cwd = Paths.get("").toAbsolutePath();
        for (Path candidate : List.of(cwd.resolve("pki"), cwd)) {
            if (Files.isDirectory(candidate.resolve("generated"))) {
                return candidate;
            }
        }
        return cwd.resolve("pki");
    }

    private static void section(String title) {
        System.out.println();
        System.out.println("--- " + title);
    }

    private static void require(boolean condition, String message) {
        if (!condition) {
            throw new CheckFailed(message);
        }
    }

    private static void check(String label, Check check) {
        try {
            record(true, label, check.run());
        } catch (CheckFailed e) {
            record(false, label, e.getMessage());
        } catch (Exception e) {
            record(false, label, e.getClass().getSimpleName() + " : " + e.getMessage());
        }
    }

    private static void record(boolean ok, String label, String detail) {
        if (ok) {
            passed++;
        } else {
            failed++;
        }
        String suffix = (detail == null || detail.isEmpty()) ? "" : "  -> " + detail;
        System.out.println("  [" + (ok ? "PASS" : "FAIL") + "] " + label + suffix);
    }
